def build_door(name, wall, s0, W, H, coll, M, leaf_mat, leaf_side="room", open_deg=0.0,
               hinge_at="end", entry=False, wall_t=WALL_T):
    """Door with frame (Zarge): jamb linings, trims on both faces, stop, leaf and handles.

    Local frame (see wall_frame): x along the wall starting at the wall-opening edge s0,
    y into the wall (hallway side at y < 0), z up. W x H is the rough wall opening.
    leaf_side "room": the leaf sits at the far side of the wall and opens away from the
    hallway (it looks recessed). "hall": the leaf sits at the hallway side (entrance door).
    """
    Mw = wall_frame(wall, s0)
    fr = M["frame"]
    jt, tw, tt = 0.025, 0.06, 0.012       # jamb thickness, trim width, trim thickness
    cx0, cx1, ch = jt, W - jt, H - jt     # clear opening
    add_box(name + "_JambA", (0, -0.001, 0), (jt, wall_t + 0.001, ch), fr, coll, Mw)
    add_box(name + "_JambB", (cx1, -0.001, 0), (W, wall_t + 0.001, ch), fr, coll, Mw)
    add_box(name + "_JambHead", (0, -0.001, ch), (W, wall_t + 0.001, H), fr, coll, Mw)
    for side, (y0, y1) in (("H", (-tt, 0.0005)), ("R", (wall_t - 0.0005, wall_t + tt))):
        add_box(name + "_Trim%sA" % side, (cx0 - tw, y0, 0), (cx0, y1, ch - 0.0005), fr, coll, Mw, bevel=0.003)
        add_box(name + "_Trim%sB" % side, (cx1, y0, 0), (cx1 + tw, y1, ch - 0.0005), fr, coll, Mw, bevel=0.003)
        add_box(name + "_Trim%sHead" % side, (cx0 - tw, y0, ch), (cx1 + tw, y1, ch + tw), fr, coll, Mw,
                bevel=0.003)
    ls, gap = 0.04, 0.003
    if leaf_side == "room":
        ly0 = wall_t - ls - 0.004
        stop = (ly0 - 0.012, ly0)
        swing = 1.0
    else:
        ly0 = 0.002
        stop = (ly0 + ls, ly0 + ls + 0.012)
        swing = -1.0
    for i, (lo, hi) in enumerate((((cx0, stop[0], 0), (cx0 + 0.012, stop[1], ch)),
                                   ((cx1 - 0.012, stop[0], 0), (cx1, stop[1], ch)),
                                   ((cx0, stop[0], ch - 0.012), (cx1, stop[1], ch)))):
        add_box(name + "_Stop%d" % i, lo, hi, fr, coll, Mw)

    lx0, lx1, lz0, lz1 = cx0 + gap, cx1 - gap, 0.008, ch - gap
    hinge_x = lx1 if hinge_at == "end" else lx0
    hinge_y = ly0 + ls if swing > 0 else ly0
    theta = math.radians(open_deg) * swing * (1.0 if hinge_at == "start" else -1.0)
    Mh = (Matrix.Translation((hinge_x, hinge_y, 0)) @ Matrix.Rotation(theta, 4, "Z")
          @ Matrix.Translation((-hinge_x, -hinge_y, 0)))
    ML = Mw @ Mh
    leaf = add_box(name + "_Leaf", (lx0, ly0, lz0), (lx1, ly0 + ls, lz1), leaf_mat, coll, ML, bevel=0.0025)

    handle_start = hinge_at == "end"
    hx = (lx0 + 0.068) if handle_start else (lx1 - 0.068)
    dirx = 1.0 if handle_start else -1.0
    hz = 1.04
    steel = M["steel"]
    for face_y, sgn in ((ly0, -1.0), (ly0 + ls, 1.0)):
        tag = "In" if sgn > 0 else "Out"
        if entry and sgn < 0:
            add_box(name + "_Plate", (hx - 0.021, face_y - 0.008, hz - 0.15), (hx + 0.021, face_y, hz + 0.10),
                    steel, coll, ML, bevel=0.003)
            add_cyl(name + "_KeyCyl", ML @ Vector((hx, face_y - 0.008, hz - 0.09)),
                    ML @ Vector((hx, face_y - 0.013, hz - 0.09)), 0.0105, M["brass_dark"], coll, seg=16)
        else:
            add_cyl(name + "_Rosette" + tag, ML @ Vector((hx, face_y, hz)),
                    ML @ Vector((hx, face_y + sgn * 0.009, hz)), 0.026, steel, coll, seg=24)
            add_cyl(name + "_Escutcheon" + tag, ML @ Vector((hx, face_y, hz - 0.09)),
                    ML @ Vector((hx, face_y + sgn * 0.007, hz - 0.09)), 0.019, steel, coll, seg=20)
        a = ML @ Vector((hx, face_y + sgn * 0.004, hz))
        b = ML @ Vector((hx, face_y + sgn * 0.058, hz))
        c = ML @ Vector((hx + dirx * 0.125, face_y + sgn * 0.062, hz - 0.004))
        add_curve(name + "_Lever" + tag, [a, b, b, c], 0.0085, steel, coll, order=3)
    if entry:
        for z in (0.22, 1.02, 1.78):
            add_cyl(name + "_Hinge%d" % int(z * 100), Mw @ Vector((lx1 + 0.002, ly0 - 0.007, z)),
                    Mw @ Vector((lx1 + 0.002, ly0 - 0.007, z + 0.11)), 0.0075, steel, coll, seg=12)
    return leaf


