def setup_render():
    sc = bpy.context.scene
    r = sc.render
    r.resolution_x, r.resolution_y = CONFIG["resolution"]
    r.resolution_percentage = CONFIG["resolution_percentage"]
    r.pixel_aspect_x = r.pixel_aspect_y = 1.0
    if CONFIG["engine"].upper() == "EEVEE":
        for ident in ("BLENDER_EEVEE_NEXT", "BLENDER_EEVEE"):
            try:
                r.engine = ident
                break
            except TypeError:
                continue
    else:
        r.engine = "CYCLES"
        cy = sc.cycles
        cy.samples = CONFIG["samples"]
        cy.preview_samples = 64
        cy.use_denoising = CONFIG["denoise"]
        if hasattr(cy, "denoiser"):
            try:
                cy.denoiser = "OPENIMAGEDENOISE"
            except TypeError:
                pass
        cy.max_bounces = 10
        cy.diffuse_bounces = 6
        cy.glossy_bounces = 4
        cy.transmission_bounces = 8
        cy.transparent_max_bounces = 16
        cy.caustics_reflective = False
        cy.caustics_refractive = False
        cy.sample_clamp_indirect = 8.0
        cy.blur_glossy = 1.0
        if hasattr(cy, "adaptive_threshold"):
            cy.use_adaptive_sampling = True
            cy.adaptive_threshold = 0.01
        if CONFIG["use_gpu"]:
            enable_gpu(sc)
    vs = sc.view_settings
    for vt in ("Standard",):
        try:
            vs.view_transform = vt
            break
        except TypeError:
            continue
    for look in ("None",):
        try:
            vs.look = look
            break
        except TypeError:
            continue
    vs.exposure = CONFIG["exposure"]
    vs.gamma = 1.0
    r.image_settings.file_format = "PNG"
    r.filepath = output_path()
    r.film_transparent = False


def output_path():
    """'//' paths are relative to the .blend; use the current folder for an unsaved file."""
    path = CONFIG["output_path"]
    if path.startswith("//") and not bpy.data.filepath:
        path = os.path.join(os.getcwd(), path[2:])
    return path


def enable_gpu(sc):
    """Render on the GPU when one is available, keeping the user's chosen backend."""
    try:
        prefs = bpy.context.preferences.addons["cycles"].preferences
    except KeyError:
        return
    current = prefs.compute_device_type
    order = ([current] if current != "NONE" else []) + ["OPTIX", "CUDA", "HIP", "METAL", "ONEAPI"]
    for backend in order:
        try:
            prefs.compute_device_type = backend
        except TypeError:
            continue
        (getattr(prefs, "refresh_devices", None) or prefs.get_devices)()
        gpus = [d for d in prefs.devices if d.type == backend]
        if gpus:
            if not any(d.use for d in gpus):
                for d in gpus:
                    d.use = True
            sc.cycles.device = "GPU"
            return
    try:
        prefs.compute_device_type = current
    except TypeError:
        pass
    sc.cycles.device = "CPU"


