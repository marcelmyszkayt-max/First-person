"""
HallwayScene.py - recreates the "dark apartment hallway" reference photo in Blender.

How to use
----------
1. Open Blender 4.2 or newer (tested with 4.2 LTS and 5.2 LTS).
2. Go to the Scripting workspace, press "Open", pick this file and press "Run Script"
   (or run it headless:  blender --background --python HallwayScene.py).
3. Press F12 to render. The camera, lens, resolution (1500 x 2000 portrait) and colour
   management are already set up to match the photo.

Everything is generated by this one file: the geometry, all textures (wallpaper with
circles, flower wall stickers, the faceted triangle rug, laminate, pictures), the
clothes, bags, shoes, the 6-spot ceiling track light, the lights and the camera.
No external files are needed. Textures are packed into the .blend when you save.

How it was matched: the camera position, rotation and focal length were solved from the
photo's vanishing points (ultra-wide phone lens, about 16 mm equivalent), and every wall,
door, shelf and coat was placed by projecting points of the photo back into 3D. The
hallway light comes from the open kitchen door on the left at the far end, which is why
the entrance door is bright and the end nearest the camera is almost black. A screen in
front of the lens adds the phone's vignette and the orange light leak on the right.

Coordinates (metres): X = right, Y = down the hallway (away from the camera),
Z = up. The camera stands at X = 0, Y = 0, 1.46 m above the floor.

Running the script again removes the previous build first.
"""

