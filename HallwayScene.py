def clear_previous():
    scene = bpy.context.scene
    if CONFIG["clear_scene"]:
        for ob in list(scene.objects):
            bpy.data.objects.remove(ob, do_unlink=True)
    for ob in list(bpy.data.objects):
        if ob.name.startswith(PFX):
            bpy.data.objects.remove(ob, do_unlink=True)
    for coll in list(bpy.data.collections):
        if coll.name.startswith(PFX):
            bpy.data.collections.remove(coll)
    pools = (bpy.data.meshes, bpy.data.curves, bpy.data.materials, bpy.data.images,
             bpy.data.lights, bpy.data.cameras, bpy.data.textures, bpy.data.worlds)
    for pool in pools:
        for block in list(pool):
            # our own data, plus (when clearing the scene) whatever that left unused
            if block.name.startswith(PFX) or (CONFIG["clear_scene"] and block.users == 0):
                try:
                    pool.remove(block)
                except (RuntimeError, ReferenceError):
                    pass


def make_collection(name, parent=None):
    coll = bpy.data.collections.new(PFX + name)
    (parent or bpy.context.scene.collection).children.link(coll)
    return coll


