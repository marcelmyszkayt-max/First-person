BOX_FACES = [(0, 3, 2, 1), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)]


def box_project_uv(me, offset, scale=1.0):
    """World-space box mapping in metres, oriented as seen from inside the room."""
    uvl = me.uv_layers.new(name="UVMap")
    co = [None] * len(me.vertices)
    for v in me.vertices:
        co[v.index] = v.co + offset
    data = []
    for poly in me.polygons:
        n = poly.normal
        ax = max(range(3), key=lambda i: abs(n[i]))
        for li in poly.loop_indices:
            p = co[me.loops[li].vertex_index]
            if ax == 0:
                u, v = (p.y if n.x > 0 else -p.y), p.z
            elif ax == 1:
                u, v = (p.x if n.y < 0 else -p.x), p.z
            else:
                u, v = p.x, (p.y if n.z > 0 else -p.y)
            data += (u * scale, v * scale)
    uvl.data.foreach_set("uv", data)


def set_smooth(ob, smooth=True):
    me = ob.data
    if hasattr(me, "polygons"):
        me.polygons.foreach_set("use_smooth", [smooth] * len(me.polygons))
        me.update()


def mesh_obj(name, verts, faces, mat, coll, uvs=None, uv_scale=1.0, center=True, smooth=False):
    verts = [Vector(v) for v in verts]
    c = Vector((0, 0, 0))
    if center and verts:
        lo = Vector((min(v.x for v in verts), min(v.y for v in verts), min(v.z for v in verts)))
        hi = Vector((max(v.x for v in verts), max(v.y for v in verts), max(v.z for v in verts)))
        c = (lo + hi) * 0.5
    me = bpy.data.meshes.new(PFX + name)
    me.from_pydata([tuple(v - c) for v in verts], [], faces)
    me.update()
    if uvs is not None:
        uvl = me.uv_layers.new(name="UVMap")
        uvl.data.foreach_set("uv", [x for uv in uvs for x in uv])
    elif uv_scale:
        box_project_uv(me, c, uv_scale)
    if mat:
        me.materials.append(mat)
    ob = bpy.data.objects.new(PFX + name, me)
    ob.location = c
    coll.objects.link(ob)
    if smooth:
        set_smooth(ob)
    return ob


def box_verts(lo, hi, M=None):
    x0, y0, z0 = lo
    x1, y1, z1 = hi
    v = [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0),
         (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)]
    if M is not None:
        v = [tuple(M @ Vector(p)) for p in v]
    return v


def add_box(name, lo, hi, mat, coll, M=None, bevel=0.0, seg=2, uv_scale=1.0):
    ob = mesh_obj(name, box_verts(lo, hi, M), BOX_FACES, mat, coll, uv_scale=uv_scale)
    if bevel > 0:
        add_bevel(ob, bevel, seg)
    return ob


def add_bevel(ob, width, seg=2):
    mod = ob.modifiers.new("Bevel", "BEVEL")
    mod.width = width
    mod.segments = seg
    mod.limit_method = "ANGLE"
    mod.harden_normals = False
    return mod


def add_subsurf(ob, levels=2):
    mod = ob.modifiers.new("Subsurf", "SUBSURF")
    mod.levels = levels
    mod.render_levels = levels
    return mod


def add_quad(name, o, u, v, mat, coll, uv=((0, 0), (1, 0), (1, 1), (0, 1))):
    o, u, v = Vector(o), Vector(u), Vector(v)
    verts = [o, o + u, o + u + v, o + v]
    return mesh_obj(name, verts, [(0, 1, 2, 3)], mat, coll, uvs=list(uv))


def bm_to_obj(name, bm, mat, coll, loc=(0, 0, 0), smooth=True, uv_scale=None):
    me = bpy.data.meshes.new(PFX + name)
    bm.to_mesh(me)
    bm.free()
    if uv_scale:
        box_project_uv(me, Vector(loc), uv_scale)
    if mat:
        me.materials.append(mat)
    ob = bpy.data.objects.new(PFX + name, me)
    ob.location = loc
    coll.objects.link(ob)
    set_smooth(ob, smooth)
    return ob


def add_cyl(name, p0, p1, r, mat, coll, seg=20, r2=None, smooth=True, caps=True):
    p0, p1 = Vector(p0), Vector(p1)
    d = p1 - p0
    bm = bmesh.new()
    bmesh.ops.create_cone(bm, cap_ends=caps, cap_tris=False, segments=seg,
                          radius1=r, radius2=r if r2 is None else r2, depth=d.length)
    rot = Vector((0, 0, 1)).rotation_difference(d.normalized()).to_matrix().to_4x4()
    bmesh.ops.transform(bm, matrix=rot, verts=bm.verts)
    ob = bm_to_obj(name, bm, mat, coll, loc=(p0 + p1) * 0.5, smooth=False)
    if smooth:
        # smooth the side, keep the caps flat
        me = ob.data
        flags = [abs(p.normal.dot(d.normalized())) < 0.5 for p in me.polygons]
        me.polygons.foreach_set("use_smooth", flags)
        me.update()
    return ob


def add_sphere(name, center, radii, mat, coll, seg=24, rings=16):
    bm = bmesh.new()
    bmesh.ops.create_uvsphere(bm, u_segments=seg, v_segments=rings, radius=1.0)
    bmesh.ops.scale(bm, vec=Vector(radii), verts=bm.verts)
    return bm_to_obj(name, bm, mat, coll, loc=center, smooth=True)


def add_curve(name, pts, radius, mat, coll, closed=False, order=4, res=10, poly=False):
    cu = bpy.data.curves.new(PFX + name, "CURVE")
    cu.dimensions = "3D"
    cu.bevel_depth = radius
    cu.bevel_resolution = 3
    cu.resolution_u = res
    cu.use_fill_caps = True
    sp = cu.splines.new("POLY" if poly else "NURBS")
    sp.points.add(len(pts) - 1)
    for i, p in enumerate(pts):
        sp.points[i].co = (p[0], p[1], p[2], 1.0)
    if not poly:
        sp.order_u = min(order, len(pts))
        sp.use_endpoint_u = not closed
    sp.use_cyclic_u = closed
    if mat:
        cu.materials.append(mat)
    ob = bpy.data.objects.new(PFX + name, cu)
    coll.objects.link(ob)
    return ob


_TEX_COUNT = [0]


def add_noise_displace(ob, strength, size, kind="CLOUDS", coords="GLOBAL", depth=2):
    _TEX_COUNT[0] += 1
    tex = bpy.data.textures.new(PFX + "noise%d" % _TEX_COUNT[0], kind)
    if hasattr(tex, "noise_scale"):
        tex.noise_scale = size
    if hasattr(tex, "noise_depth"):
        tex.noise_depth = depth
    mod = ob.modifiers.new("Displace", "DISPLACE")
    mod.texture = tex
    mod.strength = strength
    mod.mid_level = 0.5
    mod.texture_coords = coords
    return mod


def add_blob(name, center, size, mat, coll, rot=(0, 0, 0), bevel=0.35, noise=0.02,
             noise_size=0.15, levels=2):
    """Soft lumpy shape: bevelled box + subdivision + noise (bags, cushions, toys)."""
    sx, sy, sz = size
    ob = add_box(name, (-sx / 2, -sy / 2, -sz / 2), (sx / 2, sy / 2, sz / 2), mat, coll, uv_scale=1.0)
    ob.location = center
    ob.rotation_euler = rot
    add_bevel(ob, bevel * min(size), 3)
    add_subsurf(ob, levels)
    if noise:
        add_noise_displace(ob, noise, noise_size)
    set_smooth(ob)
    return ob


# Local frame for doors / wall items: x along the wall, y into the wall, z up.
def wall_frame(wall, s0):
    """Return a matrix for a wall frame. s0 = along-wall coordinate of the local origin."""
    if wall == "far":       # plane Y = FAR_Y, seen looking +Y; local x = +X
        return Matrix(((1, 0, 0, s0), (0, 1, 0, FAR_Y), (0, 0, 1, 0), (0, 0, 0, 1)))
    if wall == "right":     # plane X = RIGHT_X, seen looking +X; local x = -Y
        return Matrix(((0, 1, 0, RIGHT_X), (-1, 0, 0, s0), (0, 0, 1, 0), (0, 0, 0, 1)))
    if wall == "left":      # plane X = LEFT_FAR_X, seen looking -X; local x = +Y
        return Matrix(((0, -1, 0, LEFT_FAR_X), (1, 0, 0, s0), (0, 0, 1, 0), (0, 0, 0, 1)))
    raise ValueError(wall)


