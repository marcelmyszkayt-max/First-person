def srgb_to_lin(c):
    c = np.asarray(c, dtype=np.float64)
    return np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)


def make_image(name, rgba, linear=False):
    """rgba: (H, W, 3|4) float array of sRGB values, row 0 = top of the picture."""
    h, w = rgba.shape[:2]
    if rgba.shape[2] == 3:
        rgba = np.concatenate([rgba, np.ones((h, w, 1))], axis=2)
    img = bpy.data.images.new(PFX + name, w, h, alpha=True, float_buffer=linear)
    flat = np.ascontiguousarray(np.clip(rgba[::-1], 0, 1).astype(np.float32)).ravel()
    img.pixels.foreach_set(flat)
    img.pack()
    if linear:
        img.colorspace_settings.name = "Non-Color"
    return img


def value_noise(h, w, cells_y, cells_x, rng):
    """Periodic smooth value noise in [0, 1]."""
    g = rng.random((cells_y, cells_x))
    ys = np.arange(h) * cells_y / h
    xs = np.arange(w) * cells_x / w
    y0 = np.floor(ys).astype(int)
    x0 = np.floor(xs).astype(int)
    fy = ys - y0
    fx = xs - x0
    fy = fy * fy * (3 - 2 * fy)
    fx = fx * fx * (3 - 2 * fx)
    y1 = (y0 + 1) % cells_y
    x1 = (x0 + 1) % cells_x
    y0 %= cells_y
    x0 %= cells_x
    a = g[np.ix_(y0, x0)]
    b = g[np.ix_(y0, x1)]
    c = g[np.ix_(y1, x0)]
    d = g[np.ix_(y1, x1)]
    fx = fx[None, :]
    fy = fy[:, None]
    return (a * (1 - fx) + b * fx) * (1 - fy) + (c * (1 - fx) + d * fx) * fy


def fbm(h, w, cy, cx, rng, octaves=4):
    out = np.zeros((h, w))
    amp, tot = 1.0, 0.0
    for o in range(octaves):
        out += amp * value_noise(h, w, cy * 2 ** o, cx * 2 ** o, rng)
        tot += amp
        amp *= 0.5
    return out / tot


def blend(img, a, col):
    a = a[..., None]
    img[..., :3] = img[..., :3] * (1 - a) + np.asarray(col)[None, None, :3] * a


def draw_circle(img, cx, cy, r, col, alpha=1.0, ring=None, soft=1.0, wrap=True, inner_col=None,
                inner_alpha=0.0):
    """Anti-aliased disc or ring in pixel units, tiled seamlessly when wrap=True."""
    H, W = img.shape[:2]
    offs = [(ox, oy) for ox in (-W, 0, W) for oy in (-H, 0, H)] if wrap else [(0, 0)]
    for ox, oy in offs:
        x, y = cx + ox, cy + oy
        x0, x1 = int(max(0, x - r - 2)), int(min(W, x + r + 3))
        y0, y1 = int(max(0, y - r - 2)), int(min(H, y + r + 3))
        if x0 >= x1 or y0 >= y1:
            continue
        yy, xx = np.mgrid[y0:y1, x0:x1]
        d = np.hypot(xx + 0.5 - x, yy + 0.5 - y)
        sub = img[y0:y1, x0:x1]
        if ring:
            if inner_col is not None and inner_alpha > 0:
                ai = np.clip((r - ring - d) / soft + 0.5, 0, 1) * inner_alpha
                blend(sub, ai, inner_col)
            a = np.clip((r - d) / soft + 0.5, 0, 1) * np.clip((d - (r - ring)) / soft + 0.5, 0, 1)
        else:
            a = np.clip((r - d) / soft + 0.5, 0, 1)
        blend(sub, a * alpha, col)
        if img.shape[2] == 4:
            sub[..., 3] = np.maximum(sub[..., 3], a * alpha)


def seg_dist(xx, yy, p, q):
    px, py = p
    qx, qy = q
    dx, dy = qx - px, qy - py
    L2 = dx * dx + dy * dy + 1e-9
    t = np.clip(((xx - px) * dx + (yy - py) * dy) / L2, 0, 1)
    return np.hypot(xx - (px + t * dx), yy - (py + t * dy))


def draw_polyline(img, pts, width, col, alpha=1.0):
    H, W = img.shape[:2]
    yy, xx = np.mgrid[0:H, 0:W] + 0.5
    d = np.full((H, W), 1e9)
    for p, q in zip(pts[:-1], pts[1:]):
        d = np.minimum(d, seg_dist(xx, yy, p, q))
    a = np.clip(width / 2 - d + 0.5, 0, 1) * alpha
    blend(img, a, col)
    if img.shape[2] == 4:
        img[..., 3] = np.maximum(img[..., 3], a)


def draw_ellipse(img, cx, cy, rx, ry, ang, col, alpha=1.0):
    H, W = img.shape[:2]
    r = max(rx, ry)
    x0, x1 = int(max(0, cx - r - 2)), int(min(W, cx + r + 3))
    y0, y1 = int(max(0, cy - r - 2)), int(min(H, cy + r + 3))
    if x0 >= x1 or y0 >= y1:
        return
    yy, xx = np.mgrid[y0:y1, x0:x1] + 0.5
    ca, sa = math.cos(ang), math.sin(ang)
    u = ((xx - cx) * ca + (yy - cy) * sa) / rx
    v = (-(xx - cx) * sa + (yy - cy) * ca) / ry
    d = (np.sqrt(u * u + v * v) - 1.0) * min(rx, ry)
    a = np.clip(0.5 - d, 0, 1) * alpha
    sub = img[y0:y1, x0:x1]
    blend(sub, a, col)
    if img.shape[2] == 4:
        sub[..., 3] = np.maximum(sub[..., 3], a)


def tex_wallpaper(seed):
    """Grey 'retro circles' wallpaper strip: translucent discs, white rings, bead chains.
    Tile = 0.53 m wide x 1.06 m tall, seamless."""
    ppm = int(900 * CONFIG["texture_ppm"])
    W, H = int(0.53 * ppm), int(1.06 * ppm)
    rng = np.random.default_rng(seed)
    base = np.array([0.40, 0.41, 0.425])                   # sRGB grey
    img = np.ones((H, W, 3)) * base
    # two-tone vertical bands, like the printed strip
    band = value_noise(1, W, 1, 3, rng)[0]
    img *= (0.92 + 0.14 * band)[None, :, None]
    img *= (0.96 + 0.08 * fbm(H, W, 6, 3, rng))[..., None]
    m = ppm
    # translucent discs
    for _ in range(15):
        r = rng.uniform(0.04, 0.12) * m
        g = rng.uniform(0.62, 0.74)
        draw_circle(img, rng.uniform(0, W), rng.uniform(0, H), r, (g, g, g + 0.01),
                    alpha=rng.uniform(0.25, 0.5))
    # bead chains
    for _ in range(4):
        x = rng.uniform(0, W)
        y = rng.uniform(0, H)
        n = int(rng.integers(12, 34))
        rr = rng.uniform(0.005, 0.008) * m
        for k in range(n):
            draw_circle(img, x, y + k * 0.021 * m, rr, (0.78, 0.79, 0.80), alpha=0.85)
    # rings
    for _ in range(10):
        r = rng.uniform(0.045, 0.10) * m
        g = rng.uniform(0.74, 0.84)
        fill = rng.random() < 0.45
        draw_circle(img, rng.uniform(0, W), rng.uniform(0, H), r, (g, g, g + 0.01),
                    alpha=rng.uniform(0.6, 0.8), ring=r * rng.uniform(0.18, 0.28),
                    inner_col=(0.55, 0.56, 0.58) if fill else None, inner_alpha=0.35 if fill else 0)
    return np.clip(img, 0, 1)


def tex_flower_decal(seed, big=False):
    """Dark grey flower-and-butterflies wall sticker with alpha. 0.26 x 0.42 m."""
    ppm = int(1000 * CONFIG["texture_ppm"])
    W, H = int(0.26 * ppm), int(0.42 * ppm)
    rng = np.random.default_rng(seed)
    img = np.zeros((H, W, 4))
    img[..., :3] = 0.2
    m = ppm
    dark = (0.10, 0.10, 0.11)
    head = (0.13 * m, 0.085 * m)
    # stem: gentle S curve
    pts = []
    for i in range(24):
        t = i / 23
        x = head[0] + (0.012 * math.sin(t * 3.0 + rng.uniform(0, 1)) - 0.01 * t) * m
        y = head[1] + 0.03 * m + t * 0.30 * m
        pts.append((x, y))
    draw_polyline(img, pts, 0.0045 * m, dark)
    # leaves
    for i, t in enumerate((0.35, 0.55, 0.78)):
        p = pts[int(t * 23)]
        side = -1 if i % 2 == 0 else 1
        ang = math.radians(rng.uniform(25, 55)) * side
        L = rng.uniform(0.04, 0.06) * m
        cx = p[0] + side * L * 0.55 * math.cos(abs(ang))
        cy = p[1] - L * 0.45 * math.sin(abs(ang))
        draw_ellipse(img, cx, cy, L * 0.55, L * 0.17, -ang, dark, 0.97)
    # flower head: petals + centre
    n_pet = 12 if not big else 14
    R = (0.040 if not big else 0.05) * m
    for k in range(n_pet):
        a = k / n_pet * math.tau
        draw_ellipse(img, head[0] + math.cos(a) * R * 0.55, head[1] + math.sin(a) * R * 0.55,
                     R * 0.5, R * 0.2, a, (0.33, 0.33, 0.35) if not big else (0.16, 0.16, 0.17), 0.92)
    draw_circle(img, head[0], head[1], R * 0.42, (0.22, 0.22, 0.23), 0.95, wrap=False)
    draw_circle(img, head[0], head[1], R * 0.98, dark, 0.9, ring=0.004 * m, wrap=False)
    for k in range(9):
        a = rng.uniform(0, math.tau)
        rr = rng.uniform(0.2, 0.75) * R
        draw_circle(img, head[0] + math.cos(a) * rr, head[1] + math.sin(a) * rr, 0.004 * m,
                    (0.5, 0.5, 0.52), 0.8, wrap=False)
    # butterflies
    for _ in range(rng.integers(4, 6)):
        bx = rng.uniform(0.03, 0.23) * m
        by = rng.uniform(0.02, 0.26) * m
        if math.hypot(bx - head[0], by - head[1]) < R * 1.25:
            continue
        s = rng.uniform(0.006, 0.010) * m
        ang = rng.uniform(-0.6, 0.6)
        col = (0.07, 0.08, 0.13) if rng.random() < 0.5 else dark
        for side in (-1, 1):
            draw_ellipse(img, bx + side * s * 0.9, by - s * 0.3, s, s * 0.7, ang + side * 0.5, col, 0.95)
            draw_ellipse(img, bx + side * s * 0.6, by + s * 0.7, s * 0.6, s * 0.45, ang - side * 0.4, col, 0.95)
    return np.clip(img, 0, 1)


def tex_rug():
    """Faceted triangle rug, 1.30 m x 3.40 m. Row 0 = far end of the rug."""
    ppm = int(300 * CONFIG["texture_ppm"])
    RW, RL = 1.30, 3.40
    W, H = int(RW * ppm), int(RL * ppm)
    rng = np.random.default_rng(11)
    # jittered grid -> triangles
    nx, ny = 6, 14
    gx = np.linspace(-0.05, RW + 0.05, nx + 1)
    gy = np.linspace(-0.05, RL + 0.05, ny + 1)
    P = np.zeros((ny + 1, nx + 1, 2))
    for j in range(ny + 1):
        for i in range(nx + 1):
            jx = 0.0 if i in (0, nx) else rng.uniform(-0.07, 0.07)
            jy = 0.0 if j in (0, ny) else rng.uniform(-0.09, 0.09)
            P[j, i] = (gx[i] + jx + (0.08 if j % 2 else -0.04), gy[j] + jy)
    light = np.array([0.34, 0.35, 0.35])
    pal = [light, light * 0.93, np.array([0.41, 0.415, 0.41]), np.array([0.30, 0.31, 0.32]),
           np.array([0.26, 0.29, 0.36]), np.array([0.16, 0.19, 0.27])]
    weights = np.array([0.34, 0.2, 0.12, 0.16, 0.09, 0.09])
    tris = []
    for j in range(ny):
        for i in range(nx):
            a, b, c, d = P[j, i], P[j, i + 1], P[j + 1, i + 1], P[j + 1, i]
            if rng.random() < 0.5:
                tris += [(a, b, c), (a, c, d)]
            else:
                tris += [(a, b, d), (b, c, d)]
    # Dark facets seen in the photo (rug coordinates: u across from the left edge,
    # v along from the near end).
    forced = [((0.40, 3.35), 5), ((0.62, 2.66), 4), ((0.10, 2.22), 5), ((0.38, 1.78), 5),
              ((0.55, 1.71), 5), ((0.15, 1.33), 3), ((0.62, 0.93), 4), ((0.25, 2.93), 3),
              ((0.95, 1.30), 5), ((0.80, 0.70), 3), ((0.30, 0.45), 4), ((1.10, 2.00), 4)]
    img = np.zeros((H, W, 3)) + light
    yy, xx = np.mgrid[0:H, 0:W] + 0.5
    U = xx / ppm
    V = RL - yy / ppm
    edge = np.full((H, W), 1e9)
    for tri in tris:
        (x1, y1), (x2, y2), (x3, y3) = tri
        det = (y2 - y3) * (x1 - x3) + (x3 - x2) * (y1 - y3)
        if abs(det) < 1e-9:
            continue
        c0 = int(max(0, min(x1, x2, x3) * ppm - 3))
        c1 = int(min(W, max(x1, x2, x3) * ppm + 4))
        r0 = int(max(0, (RL - max(y1, y2, y3)) * ppm - 3))
        r1 = int(min(H, (RL - min(y1, y2, y3)) * ppm + 4))
        if c0 >= c1 or r0 >= r1:
            continue
        u = U[r0:r1, c0:c1]
        v = V[r0:r1, c0:c1]
        l1 = ((y2 - y3) * (u - x3) + (x3 - x2) * (v - y3)) / det
        l2 = ((y3 - y1) * (u - x3) + (x1 - x3) * (v - y3)) / det
        inside = (l1 >= 0) & (l2 >= 0) & (1 - l1 - l2 >= 0)
        col = pal[rng.choice(len(pal), p=weights)]
        for (fu, fv), k in forced:
            f1 = ((y2 - y3) * (fu - x3) + (x3 - x2) * (fv - y3)) / det
            f2 = ((y3 - y1) * (fu - x3) + (x1 - x3) * (fv - y3)) / det
            if f1 >= 0 and f2 >= 0 and 1 - f1 - f2 >= 0:
                col = pal[k]
        img[r0:r1, c0:c1][inside] = col
        e = edge[r0:r1, c0:c1]
        for p, q in ((tri[0], tri[1]), (tri[1], tri[2]), (tri[2], tri[0])):
            np.minimum(e, seg_dist(u, v, p, q) * ppm, out=e)
    # thin darker seams between facets
    img *= (1 - 0.35 * np.clip(1.6 - edge, 0, 1))[..., None]
    # border
    bd = np.minimum.reduce([U, RW - U, V, RL - V]) * ppm
    img *= (1 - 0.25 * np.clip(0.012 * ppm - bd, 0, 1) / (0.012 * ppm))[..., None]
    # pile mottling
    img *= (0.9 + 0.2 * fbm(H, W, 40, 12, rng, 3))[..., None]
    return np.clip(img, 0, 1)


def tex_laminate():
    """Warm oak laminate, planks run along the hallway. Tile 0.76 m x 2.56 m."""
    ppm = int(400 * CONFIG["texture_ppm"])
    TW, TL = 0.76, 2.56
    W, H = int(TW * ppm), int(TL * ppm)
    rng = np.random.default_rng(5)
    img = np.zeros((H, W, 3))
    pw = TW / 4
    grain = fbm(H, W, 6, 90, rng, 4)              # streaks along the plank
    fine = value_noise(H, W, 300, 400, rng)
    knots = fbm(H, W, 24, 8, rng, 3)
    yy, xx = np.mgrid[0:H, 0:W]
    U = (xx + 0.5) / ppm
    V = (yy + 0.5) / ppm
    col_i = np.minimum((U / pw).astype(int), 3)
    stagger = np.array([0.0, 0.62, 1.31, 0.33])
    vv = (V + stagger[col_i]) % TL
    row_i = (vv / (TL / 2)).astype(int)
    plank_id = col_i * 2 + row_i
    tone = rng.uniform(0.86, 1.12, 8)
    hue = rng.uniform(-0.03, 0.03, 8)
    base = np.array([0.42, 0.31, 0.245])
    t = tone[plank_id][..., None]
    h = hue[plank_id]
    img[:] = base
    img = img * t + np.stack([h, h * 0.4, -h * 0.4], -1)
    img *= (0.78 + 0.32 * grain)[..., None]
    img *= (0.95 + 0.08 * fine)[..., None]
    img *= (0.9 + 0.1 * knots)[..., None]
    # V-groove joints
    du = np.abs(((U + pw / 2) % pw) - pw / 2)
    dv = np.abs(((vv + TL / 4) % (TL / 2)) - TL / 4)
    joint = np.clip(1.5 - np.minimum(du, dv) * ppm, 0, 1)
    img *= (1 - 0.45 * joint)[..., None]
    return np.clip(img, 0, 1)


