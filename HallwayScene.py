def build_garment(name, top, yaw, w_top, w_bot, depth, length, mat, coll, seed=0, folds=5, hood=False,
                  taper=True, subsurf=1, sleeves=True, sleeve_len=None, sway=0.03):
    """Hanging coat: a flattened soft tube (body) with two sleeves, hung from `top`.

    Local axes: x = across the shoulders, y = front/back, z = up. `yaw` turns it in
    degrees. The shoulders narrow towards the hook unless taper=False (used for the
    knit stripes that wrap a jacket)."""
    rng = random.Random(seed)
    n_rings, n_seg = 22, 28
    verts, faces = [], []
    ph = [rng.uniform(0, math.tau) for _ in range(4)]
    for i in range(n_rings):
        s = i / (n_rings - 1)
        shoulder = min(1.0, s / 0.12) if taper else 1.0
        sh = math.sin(shoulder * math.pi / 2)
        w = (w_top + (w_bot - w_top) * s ** 1.3) * (0.30 + 0.70 * sh)
        d = depth * (0.45 + 0.55 * sh) * (1.0 - 0.25 * s)
        z = -s * length
        off_x = sway * math.sin(s * 2.2 + ph[2]) * s
        off_y = 0.25 * sway * math.sin(s * 3.1 + ph[3]) * s
        for j in range(n_seg):
            th = j / n_seg * math.tau
            rf = (1.0 + 0.09 * s * math.sin(folds * th + ph[0] + 2.0 * s)
                  + 0.035 * math.sin(3 * th + ph[1]) + 0.02 * math.sin(11 * th + 5 * s))
            x = 0.5 * w * math.cos(th) * rf + off_x
            y = 0.5 * d * math.sin(th) * rf + off_y
            verts.append((x, y, z))
    for i in range(n_rings - 1):
        for j in range(n_seg):
            a = i * n_seg + j
            b = i * n_seg + (j + 1) % n_seg
            faces.append((a, b, b + n_seg, a + n_seg))
    top_c = len(verts)
    verts.append((0, 0, 0.005))
    bot_c = len(verts)
    verts.append((0, 0, -length * 0.98))
    last = (n_rings - 1) * n_seg
    for j in range(n_seg):
        faces.append((top_c, (j + 1) % n_seg, j))
        faces.append((bot_c, last + j, last + (j + 1) % n_seg))
    R = Matrix.Translation(top) @ Matrix.Rotation(math.radians(yaw), 4, "Z")
    wverts = [tuple(R @ Vector(v)) for v in verts]
    ob = mesh_obj(name, wverts, faces, mat, coll, uv_scale=1.0, smooth=True)
    if subsurf:
        add_subsurf(ob, subsurf)
    if not taper:
        return ob
    if sleeves:
        sl = sleeve_len or length * 0.62
        for side in (-1, 1):
            sx = side * (w_top * 0.5 + 0.02)
            pts = [(sx, 0.0, -0.07),
                   (sx + side * 0.035, depth * 0.10, -0.07 - sl * 0.35),
                   (sx + side * 0.02 + rng.uniform(-0.02, 0.02), depth * 0.18, -0.07 - sl * 0.75),
                   (sx + rng.uniform(-0.03, 0.03), depth * 0.15, -0.07 - sl)]
            sleeve = add_curve(name + "_Sleeve%d" % (side > 0), [tuple(R @ Vector(p)) for p in pts],
                               min(0.065, max(0.04, w_top * 0.16)), mat, coll, order=3)
            sleeve.data.bevel_resolution = 4
    if hood:
        hp = R @ Vector((0, -depth * 0.25, -0.05))
        add_blob(name + "_Hood", hp, (w_top * 0.95, depth * 0.85, 0.22), mat, coll,
                 rot=(0.25, 0, math.radians(yaw)), noise=0.012, levels=2)
    else:
        cp = R @ Vector((0, -depth * 0.05, -0.035))
        add_blob(name + "_Collar", cp, (w_top * 0.75, depth * 0.7, 0.07), mat, coll,
                 rot=(0, 0, math.radians(yaw)), noise=0.006, levels=2)
    return ob


