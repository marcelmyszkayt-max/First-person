_MATS = {}


def new_material(name):
    m = bpy.data.materials.new(PFX + name)
    if bpy.app.version < (5, 0, 0):
        m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    out = nt.nodes.new("ShaderNodeOutputMaterial")
    out.location = (600, 0)
    return m, nt, out


def set_in(node, name, value):
    sock = node.inputs.get(name)
    if sock is not None:
        try:
            sock.default_value = value
        except (TypeError, ValueError):
            pass


def lin(c):
    """sRGB 0-1 triple -> linear RGBA tuple."""
    l = srgb_to_lin(c[:3])
    return (float(l[0]), float(l[1]), float(l[2]), 1.0)


def mat_basic(name, color, rough=0.5, metal=0.0, spec=0.5, coat=0.0, sheen=0.0,
              emit=None, emit_strength=0.0, bump=0.0, bump_scale=200.0, srgb=True):
    if name in _MATS:
        return _MATS[name]
    m, nt, out = new_material(name)
    b = nt.nodes.new("ShaderNodeBsdfPrincipled")
    set_in(b, "Base Color", lin(color) if srgb else tuple(color) + (1.0,))
    set_in(b, "Roughness", rough)
    set_in(b, "Metallic", metal)
    set_in(b, "Specular IOR Level", spec)
    set_in(b, "Coat Weight", coat)
    set_in(b, "Sheen Weight", sheen)
    if emit is not None:
        set_in(b, "Emission Color", lin(emit))
        set_in(b, "Emission Strength", emit_strength)
    if bump > 0:
        tc = nt.nodes.new("ShaderNodeTexCoord")
        nz = nt.nodes.new("ShaderNodeTexNoise")
        set_in(nz, "Scale", bump_scale)
        set_in(nz, "Detail", 6.0)
        bp = nt.nodes.new("ShaderNodeBump")
        set_in(bp, "Strength", bump)
        set_in(bp, "Distance", 0.002)
        nt.links.new(tc.outputs["Object"], nz.inputs["Vector"])
        nt.links.new(nz.outputs["Fac"], bp.inputs["Height"])
        nt.links.new(bp.outputs["Normal"], b.inputs["Normal"])
    nt.links.new(b.outputs[0], out.inputs["Surface"])
    _MATS[name] = m
    return m


def mat_image(name, img, scale=(1.0, 1.0), rough=0.6, spec=0.5, bump=0.0, bump_scale=300.0,
              alpha=False, tint=None, sheen=0.0, coat=0.0, interp="Linear"):
    m, nt, out = new_material(name)
    tc = nt.nodes.new("ShaderNodeTexCoord")
    mp = nt.nodes.new("ShaderNodeMapping")
    set_in(mp, "Scale", (scale[0], scale[1], 1.0))
    it = nt.nodes.new("ShaderNodeTexImage")
    it.image = img
    it.interpolation = interp
    it.extension = "REPEAT"
    b = nt.nodes.new("ShaderNodeBsdfPrincipled")
    set_in(b, "Roughness", rough)
    set_in(b, "Specular IOR Level", spec)
    set_in(b, "Sheen Weight", sheen)
    set_in(b, "Coat Weight", coat)
    nt.links.new(tc.outputs["UV"], mp.inputs["Vector"])
    nt.links.new(mp.outputs["Vector"], it.inputs["Vector"])
    col_out = it.outputs["Color"]
    if tint is not None:
        mix = nt.nodes.new("ShaderNodeMix")
        mix.data_type = "RGBA"
        mix.blend_type = "MULTIPLY"
        _sock(mix.inputs, "Factor_Float").default_value = 1.0
        _sock(mix.inputs, "B_Color").default_value = lin(tint)
        nt.links.new(col_out, _sock(mix.inputs, "A_Color"))
        col_out = _sock(mix.outputs, "Result_Color")
    nt.links.new(col_out, b.inputs["Base Color"])
    if bump > 0:
        nz = nt.nodes.new("ShaderNodeTexNoise")
        set_in(nz, "Scale", bump_scale)
        set_in(nz, "Detail", 8.0)
        bp = nt.nodes.new("ShaderNodeBump")
        set_in(bp, "Strength", bump)
        set_in(bp, "Distance", 0.003)
        nt.links.new(tc.outputs["Object"], nz.inputs["Vector"])
        nt.links.new(nz.outputs["Fac"], bp.inputs["Height"])
        nt.links.new(bp.outputs["Normal"], b.inputs["Normal"])
    if alpha:
        tr = nt.nodes.new("ShaderNodeBsdfTransparent")
        mx = nt.nodes.new("ShaderNodeMixShader")
        nt.links.new(it.outputs["Alpha"], mx.inputs[0])
        nt.links.new(tr.outputs[0], mx.inputs[1])
        nt.links.new(b.outputs[0], mx.inputs[2])
        nt.links.new(mx.outputs[0], out.inputs["Surface"])
        _blend_mode(m)
    else:
        nt.links.new(b.outputs[0], out.inputs["Surface"])
    return m


def _sock(coll, ident):
    for s in coll:
        if s.identifier == ident:
            return s
    return coll[0]


def _blend_mode(m):
    for attr, val in (("surface_render_method", "DITHERED"), ("blend_method", "HASHED")):
        if hasattr(m, attr):
            try:
                setattr(m, attr, val)
            except (TypeError, ValueError):
                pass


def mat_wood(name, light, dark, rough=0.45, axis="Z", rings=22.0, coat=0.15, spec=0.5):
    """Procedural wood: growth rings around `axis` plus stretched noise streaks."""
    if name in _MATS:
        return _MATS[name]
    m, nt, out = new_material(name)
    tc = nt.nodes.new("ShaderNodeTexCoord")
    stretch = {"X": (0.06, 1.0, 1.0), "Y": (1.0, 0.06, 1.0), "Z": (1.0, 1.0, 0.06)}[axis]
    mp = nt.nodes.new("ShaderNodeMapping")
    set_in(mp, "Scale", stretch)
    wv = nt.nodes.new("ShaderNodeTexWave")
    wv.wave_type = "RINGS"
    try:
        wv.rings_direction = axis
    except (TypeError, AttributeError):
        pass
    set_in(wv, "Scale", rings)
    set_in(wv, "Distortion", 5.0)
    set_in(wv, "Detail", 3.0)
    set_in(wv, "Detail Scale", 1.5)
    nz = nt.nodes.new("ShaderNodeTexNoise")
    set_in(nz, "Scale", 70.0)
    set_in(nz, "Detail", 8.0)
    nt.links.new(tc.outputs["Object"], wv.inputs["Vector"])
    nt.links.new(tc.outputs["Object"], mp.inputs["Vector"])
    nt.links.new(mp.outputs["Vector"], nz.inputs["Vector"])
    a = nt.nodes.new("ShaderNodeMath")
    a.operation = "MULTIPLY"
    set_in_idx(a, 1, 0.6)
    nt.links.new(wv.outputs["Fac"], a.inputs[0])
    b2 = nt.nodes.new("ShaderNodeMath")
    b2.operation = "MULTIPLY_ADD"
    set_in_idx(b2, 1, 0.5)
    nt.links.new(nz.outputs["Fac"], b2.inputs[0])
    nt.links.new(a.outputs[0], b2.inputs[2])
    ramp = nt.nodes.new("ShaderNodeValToRGB")
    ramp.color_ramp.elements[0].position = 0.15
    ramp.color_ramp.elements[1].position = 0.95
    ramp.color_ramp.elements[0].color = lin(dark)
    ramp.color_ramp.elements[1].color = lin(light)
    nt.links.new(b2.outputs[0], ramp.inputs["Fac"])
    b = nt.nodes.new("ShaderNodeBsdfPrincipled")
    set_in(b, "Roughness", rough)
    set_in(b, "Coat Weight", coat)
    set_in(b, "Coat Roughness", 0.25)
    set_in(b, "Specular IOR Level", spec)
    nt.links.new(ramp.outputs["Color"], b.inputs["Base Color"])
    nt.links.new(b.outputs[0], out.inputs["Surface"])
    _MATS[name] = m
    return m


