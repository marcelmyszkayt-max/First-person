def add_light(name, kind, loc, energy, color, coll, size=0.1, rot=None, target=None, spot=None, blend=0.5,
              size_y=None, shadow_soft=None):
    ld = bpy.data.lights.new(PFX + name, kind)
    ld.energy = energy
    ld.color = color
    if kind == "AREA":
        ld.shape = "RECTANGLE" if size_y else "DISK"
        ld.size = size
        if size_y:
            ld.size_y = size_y
    elif kind in ("POINT", "SPOT"):
        ld.shadow_soft_size = size if shadow_soft is None else shadow_soft
    if kind == "SPOT":
        ld.spot_size = spot
        ld.spot_blend = blend
        if hasattr(ld, "show_cone"):
            ld.show_cone = False
    ob = bpy.data.objects.new(PFX + name, ld)
    ob.location = loc
    coll.objects.link(ob)
    if target is not None:
        d = Vector(target) - Vector(loc)
        ob.rotation_euler = d.to_track_quat("-Z", "Y").to_euler()
    elif rot is not None:
        ob.rotation_euler = rot
    return ob


def kelvin(t):
    """Approximate blackbody colour (linear RGB) for a colour temperature in K."""
    t = t / 100.0
    if t <= 66:
        r = 1.0
        g = max(0.0, min(1.0, (99.4708025861 * math.log(t) - 161.1195681661) / 255))
        b = 0.0 if t <= 19 else max(0.0, min(1.0, (138.5177312231 * math.log(t - 10) - 305.0447927307) / 255))
    else:
        r = max(0.0, min(1.0, 329.698727446 * (t - 60) ** -0.1332047592 / 255))
        g = max(0.0, min(1.0, 288.1221695283 * (t - 60) ** -0.0755148492 / 255))
        b = 1.0
    l = srgb_to_lin((r, g, b))
    return (float(l[0]), float(l[1]), float(l[2]))


