def build_drape(name, xr, yr, bumps, mat, coll, res=(30, 34), lift=0.025, seed=9):
    """A piece of cloth thrown over things: a heightfield over (x, y) that follows the
    given elliptical bumps (cx, cy, rx, ry, top) and sags down between and around them."""
    rng = random.Random(seed)
    nx, ny = res
    x0, x1 = xr
    y0, y1 = yr
    verts, faces = [], []
    waves = [(rng.uniform(6, 14), rng.uniform(6, 14), rng.uniform(0, 6.3)) for _ in range(4)]
    for j in range(ny + 1):
        for i in range(nx + 1):
            x = x0 + (x1 - x0) * i / nx
            y = y0 + (y1 - y0) * j / ny
            h = 0.03
            for cx, cy, rx, ry, top in bumps:
                d2 = ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2
                if d2 < 1.0:
                    h = max(h, top * math.sqrt(1.0 - d2) ** 0.6 + lift)
                else:
                    h = max(h, (top + lift) * math.exp(-(math.sqrt(d2) - 1.0) * 3.2))
            # edges fall towards the floor
            ex = min(i, nx - i) / nx
            ey = min(j, ny - j) / ny
            h *= min(1.0, 0.45 + 4.0 * min(ex, ey))
            for kx, ky, ph in waves:
                h += 0.008 * math.sin(kx * x + ky * y + ph)
            verts.append((x, y, max(0.005, h)))
    for j in range(ny):
        for i in range(nx):
            a = j * (nx + 1) + i
            faces.append((a, a + 1, a + nx + 2, a + nx + 1))
    ob = mesh_obj(name, verts, faces, mat, coll, uv_scale=1.0, smooth=True)
    sol = ob.modifiers.new("Solidify", "SOLIDIFY")
    sol.thickness = 0.012
    add_subsurf(ob, 1)
    add_noise_displace(ob, 0.008, 0.05)
    return ob


RUG_W, RUG_L = 1.30, 3.40           # big hallway rug, the bag pile stands on its right half
RUG_CORNER = (0.09, 3.82)           # far-left corner
RUG_ANGLE = -4.0                    # degrees; the near end swings slightly to the left


def build_rug(coll, M):
    W, L, T = RUG_W, RUG_L, 0.009
    Mr = (Matrix.Translation((RUG_CORNER[0], RUG_CORNER[1], 0.0)) @ Matrix.Rotation(math.radians(RUG_ANGLE), 4, "Z")
          @ Matrix.Translation((0.0, -L, 0.0)))
    local = box_verts((0, 0, 0), (W, L, T))
    verts = [tuple(Mr @ Vector(p)) for p in local]
    uvs = []
    for face in BOX_FACES:
        for vi in face:
            u, v, _ = local[vi]
            uvs.append((u / W, v / L))
    rug = mesh_obj("Rug", verts, BOX_FACES, M["rug"], coll, uvs=uvs)
    add_bevel(rug, 0.003, 2)
    return rug


def build_sneaker(name, xy, yaw_deg, kind, on_side, coll, M):
    x, y = xy
    L, Wd = 0.28, 0.10
    white = M["sneaker_white"] if kind == "white" else M["slipper_blue"]
    R = Matrix.Translation((x, y, 0)) @ Matrix.Rotation(math.radians(yaw_deg), 4, "Z")
    if on_side:
        R = R @ Matrix.Translation((0, 0, Wd / 2)) @ Matrix.Rotation(math.radians(80), 4, "X") \
            @ Matrix.Translation((0, 0, -Wd / 2))
    # sole
    sole = add_box(name + "_Sole", (-L / 2, -Wd / 2, 0), (L / 2, Wd / 2, 0.028), M["rubber_white"], coll, R)
    add_bevel(sole, 0.012, 3)
    # upper: squashed ellipsoid, higher at the heel
    bm = bmesh.new()
    bmesh.ops.create_uvsphere(bm, u_segments=24, v_segments=14, radius=1.0)
    for v in bm.verts:
        px, py, pz = v.co
        h = 0.055 + 0.03 * max(0.0, -px)          # heel higher
        v.co = Vector((px * L * 0.49, py * Wd * 0.47, max(pz, -0.2) * h + 0.03))
    me_ob = bm_to_obj(name + "_Upper", bm, white, coll, smooth=True)
    me_ob.matrix_world = R
    add_subsurf(me_ob, 1)
    # opening / insole
    op = add_sphere(name + "_Opening", (0, 0, 0), (0.055, 0.035, 0.012), M["shoe_inside"], coll)
    op.matrix_world = R @ Matrix.Translation((-0.06, 0, 0.083))


